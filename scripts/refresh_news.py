#!/usr/bin/env python3
"""Refresh problematic stored news. Defaults to a read-only candidate report.

Run from the server checkout, using its virtualenv and .env:
  python scripts/refresh_news.py
  python scripts/refresh_news.py --apply --limit 5
  python scripts/refresh_news.py --apply --slug some-article
  python scripts/refresh_news.py --apply --all

Each applied article has a JSON backup, and body + media change in one DB
transaction. Old image files stay on disk; new mirrors use a fresh namespace.
Titles, excerpts, slugs and source URLs are preserved. Changed English bodies
invalidate body_uk; translation is regenerated by the website on a later view.
Restart neowatch after applying to clear its in-process news cache.
"""
import argparse
from collections import Counter, defaultdict
from datetime import datetime, timezone
from html import unescape
import json
import logging
import os
from pathlib import Path
import re
import sys
import time
import uuid

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

logger = logging.getLogger('refresh_news')
MEDIA = re.compile(r'\[(IMG|VIDEO):(\d+)\]')
PROMO = re.compile(r'Andy has been interested in space exploration|About the Author|Follow us on', re.I)


def connection():
    from database.pool import get_db_connection
    return get_db_connection()


def snapshot_from_cursor(cursor, article_id, *, lock=False):
    suffix = ' FOR UPDATE' if lock else ''
    cursor.execute('SELECT * FROM news_articles WHERE id = %s' + suffix, (article_id,))
    article = cursor.fetchone()
    if not article:
        return None
    result = {'article': article}
    for key, table in [('images', 'news_article_images'), ('videos', 'news_article_videos')]:
        cursor.execute(f'SELECT * FROM {table} WHERE article_id = %s ORDER BY position' + suffix, (article_id,))
        result[key] = cursor.fetchall()
    return result


def load_snapshots(connect=connection):
    """Read one consistent snapshot of all rows, without source requests."""
    conn = connect()
    cursor = None
    try:
        cursor = conn.cursor(dictionary=True)
        cursor.execute('SELECT * FROM news_articles ORDER BY id')
        articles = cursor.fetchall()
        media = {}
        for key, table in [('images', 'news_article_images'), ('videos', 'news_article_videos')]:
            grouped = defaultdict(list)
            cursor.execute(f'SELECT * FROM {table} ORDER BY article_id, position')
            for row in cursor.fetchall():
                grouped[row['article_id']].append(row)
            media[key] = grouped
        return [{'article': row, 'images': media['images'][row['id']], 'videos': media['videos'][row['id']]} for row in articles]
    finally:
        conn.rollback()  # End the read transaction; never write during selection.
        if cursor is not None:
            cursor.close()
        conn.close()


def invalid_cached_image(relative, media_root):
    if not relative:
        return False  # A remote fallback without a mirror is valid.
    root = media_root.resolve()
    path = (root / relative).resolve()
    if not path.is_relative_to(root):
        return True
    try:
        from PIL import Image
        with Image.open(path) as image:
            image.verify()
        return False
    except (OSError, ValueError):
        return True


def candidate_reasons(snapshot, *, media_root=None):
    article = snapshot['article']
    body = article.get('body') or ''
    reasons = []
    if not body.strip() or body == article.get('excerpt'):
        reasons.append('missing_full_body')
    if not (article.get('image') or '').strip():
        reasons.append('missing_cover')
    if body.strip() == 'Go back to Earth to get your bearings.':
        reasons.append('publisher_error_template')
    if PROMO.search(body):
        reasons.append('author_or_promo')
    if article.get('body_uk') and set(MEDIA.findall(article['body_uk'])) != set(MEDIA.findall(body)):
        reasons.append('translation_media_mismatch')
    expected = defaultdict(set)
    for kind, position in MEDIA.findall(body):
        expected[kind].add(int(position))
    for key, kind, url_key in [('images', 'IMG', 'source_url'), ('videos', 'VIDEO', 'video_url')]:
        actual = {row['position'] for row in snapshot[key] if row.get(url_key)}
        if expected[kind] - actual:
            reasons.append(f'missing_{key}')
        if actual - expected[kind]:
            reasons.append(f'unused_{key}')
    urls = [article.get('image') or ''] + [row.get('source_url') or '' for row in snapshot['images']] + [row.get('video_url') or '' for row in snapshot['videos']]
    if any(unescape(url) != url for url in urls):
        reasons.append('encoded_media_url')
    if media_root is not None and any(invalid_cached_image(row.get('full_path'), media_root) for row in snapshot['images']):
        reasons.append('invalid_image_cache')
    return reasons


def validate_content(snapshot, content):
    from parsers.news_html import media_url
    body = (content.get('body') or '').strip()
    prose = MEDIA.sub('', body).strip()
    if len(prose) < 80:
        raise ValueError('source_empty_or_too_short: original article kept')
    old_prose = MEDIA.sub('', snapshot['article'].get('body') or '').strip()
    if len(old_prose) >= 1000 and len(prose) < len(old_prose) / 4:
        raise ValueError('source_suspiciously_short: original article kept')
    images = content.get('body_images') or []
    videos = content.get('body_videos') or []
    if '[VIDEO:' in (snapshot['article'].get('body') or '') and not videos:
        raise ValueError('source_has_no_videos: original article kept')
    for kind, position in MEDIA.findall(body):
        items = images if kind == 'IMG' else videos
        if int(position) >= len(items):
            raise ValueError('source_has_unresolved_media')
    for url in images + videos:
        if not isinstance(url, str) or len(url) > 500 or not media_url(url):
            raise ValueError('source_has_invalid_media_url')
    if len(content.get('image') or '') > 500:
        raise ValueError('source_cover_url_too_long')


def stage_images(article_id, content, run_id):
    from services.news_images import download_news_image
    # Generated path components only. Never clear or overwrite the old cache.
    namespace = f'_refresh/{int(article_id)}/{run_id}'
    rows = []
    for position, src in enumerate(content.get('body_images') or []):
        full, thumb = download_news_image(namespace, position, src)
        if not full:
            logger.warning('id=%s image=%s: mirror failed; keeping the remote URL', article_id, position)
        rows.append({'position': position, 'source_url': src, 'full_path': full, 'thumb_path': thumb})
    return rows


def write_backup(path, snapshot):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('x', encoding='utf-8') as stream:
        json.dump({'format': 1, 'saved_at': datetime.now(timezone.utc).isoformat(), **snapshot}, stream, ensure_ascii=False, indent=2, default=str)
        stream.flush()
        os.fsync(stream.fileno())


def apply_refresh(snapshot, content, image_rows, backup_path, *, connect=connection):
    """Lock, check for concurrent edits, back up, then replace atomically."""
    validate_content(snapshot, content)
    article = snapshot['article']
    article_id = article['id']
    body = content['body'].strip()
    body_uk = article.get('body_uk') if body == (article.get('body') or '') else None
    if body_uk:
        counts = {'IMG': len(image_rows), 'VIDEO': len(content.get('body_videos') or [])}
        if set(MEDIA.findall(body_uk)) != set(MEDIA.findall(body)) or any(int(position) >= counts[kind] for kind, position in MEDIA.findall(body_uk)):
            body_uk = None
    image = content.get('image') or unescape(article.get('image') or '') or None
    conn = connect()
    cursor = None
    try:
        cursor = conn.cursor(dictionary=True)
        current = snapshot_from_cursor(cursor, article_id, lock=True)
        if current != snapshot:
            raise ValueError('concurrent_edit: original article kept; rerun selection')
        write_backup(backup_path, current)  # Any backup failure aborts before SQL writes.
        cursor.execute('UPDATE news_articles SET body = %s, body_uk = %s, image = %s WHERE id = %s', (body, body_uk, image, article_id))
        cursor.execute('DELETE FROM news_article_images WHERE article_id = %s', (article_id,))
        cursor.execute('DELETE FROM news_article_videos WHERE article_id = %s', (article_id,))
        for row in image_rows:
            cursor.execute('INSERT INTO news_article_images (article_id, position, source_url, full_path, thumb_path) VALUES (%s, %s, %s, %s, %s)',
                           (article_id, row['position'], row['source_url'], row['full_path'], row['thumb_path']))
        for position, src in enumerate(content.get('body_videos') or []):
            cursor.execute('INSERT INTO news_article_videos (article_id, position, video_url) VALUES (%s, %s, %s)', (article_id, position, src))
        conn.commit()
    except BaseException:
        conn.rollback()
        raise
    finally:
        if cursor is not None:
            cursor.close()
        conn.close()


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--apply', action='store_true', help='Fetch sources, back up and update selected articles')
    mode.add_argument('--dry-run', action='store_true', help='Only list candidates (the default); no HTTP requests or DB writes')
    parser.add_argument('--all', action='store_true', help='Select all source articles, including ones without detected problems')
    parser.add_argument('--slug', action='append', default=[], help='Select an exact slug; repeat for multiple articles')
    parser.add_argument('--limit', type=int, help='Maximum number of selected articles')
    parser.add_argument('--after-id', type=int, default=0, help='Resume after this article ID (useful with --limit)')
    parser.add_argument('--delay', type=float, default=1.0, help='Pause between source requests, seconds (default: 1)')
    parser.add_argument('--backup-dir', type=Path, default=Path('data/news-refresh'), help='Backup/report root, relative to the repository')
    args = parser.parse_args(argv)
    if args.limit is not None and args.limit < 1:
        parser.error('--limit must be positive')
    if args.delay < 0:
        parser.error('--delay must be non-negative')
    if args.after_id < 0:
        parser.error('--after-id must be non-negative')
    if args.all and args.slug:
        parser.error('Choose --all or --slug, not both')
    os.chdir(ROOT)
    logging.basicConfig(level=logging.INFO, format='%(asctime)s %(levelname)s %(message)s')
    snapshots = load_snapshots()
    requested = set(args.slug)
    missing = requested - {row['article'].get('slug') for row in snapshots}
    if missing:
        parser.error('Unknown slugs: ' + ', '.join(sorted(missing)))
    selected = []
    for snapshot in snapshots:
        article = snapshot['article']
        if article['id'] <= args.after_id:
            continue
        if not str(article.get('url') or '').startswith(('https://', 'http://')):
            continue
        if requested and article.get('slug') not in requested:
            continue
        reasons = candidate_reasons(snapshot, media_root=ROOT / 'data/news')
        if requested or args.all or reasons:
            selected.append((snapshot, reasons or ['explicit_selection']))
    if args.limit:
        selected = selected[:args.limit]
    logger.info('Selected %s of %s articles; mode=%s', len(selected), len(snapshots), 'APPLY' if args.apply else 'DRY RUN')
    if selected:
        logger.info('Last selected ID: %s (resume with --after-id %s)', selected[-1][0]['article']['id'], selected[-1][0]['article']['id'])
    for snapshot, reasons in selected:
        logger.info('id=%s slug=%s reasons=%s', snapshot['article']['id'], snapshot['article'].get('slug'), ','.join(reasons))
    if not args.apply or not selected:
        return 0
    from parsers.news import NewsParser
    run_id = datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ') + '-' + uuid.uuid4().hex[:8]
    run_dir = args.backup_dir / run_id
    run_dir.mkdir(parents=True, exist_ok=False)
    logger.info('Backups and result log: %s', run_dir.resolve())
    results = []
    for index, (snapshot, reasons) in enumerate(selected):
        article = snapshot['article']
        result = {'id': article['id'], 'slug': article.get('slug'), 'reasons': reasons}
        try:
            content = NewsParser.get_article_content(article['url'])
            validate_content(snapshot, content)
            images = stage_images(article['id'], content, run_id)
            backup = run_dir / f"{article['id']}.json"
            apply_refresh(snapshot, content, images, backup)
            result.update(status='updated', backup=str(backup), images=len(images), videos=len(content.get('body_videos') or []))
            logger.info('UPDATED id=%s slug=%s images=%s videos=%s', article['id'], article.get('slug'), result['images'], result['videos'])
        except Exception as exc:
            result.update(status='failed', error=str(exc))
            logger.error('FAILED id=%s slug=%s: %s', article['id'], article.get('slug'), exc)
        results.append(result)
        # JSONL is durable after each article, including interruption of the run.
        with (run_dir / 'results.jsonl').open('a', encoding='utf-8') as stream:
            stream.write(json.dumps(result, ensure_ascii=False) + '\n')
            stream.flush()
            os.fsync(stream.fileno())
        if index + 1 < len(selected):
            time.sleep(args.delay)
    counts = Counter(row['status'] for row in results)
    logger.info('Done: updated=%s failed=%s. Restart neowatch to clear its news cache.', counts['updated'], counts['failed'])
    return 1 if counts['failed'] else 0


if __name__ == '__main__':
    sys.exit(main())
